"""
IntelliCrash Hardware — Phase 2 Preprocessing Pipeline
======================================================
Handles data loading, block-stratified splitting, edge trimming,
RobustScaler fitting (train only), and saving preprocessed .npy arrays.
"""

import os
import json
import numpy as np
from pathlib import Path
from sklearn.model_selection import StratifiedShuffleSplit
from sklearn.preprocessing import RobustScaler

SEED = 42
BLOCK_SIZE = 20
EDGE_TRIM = 3  # windows dropped at each block edge to prevent overlap leakage

HARDWARE_DIR = Path(__file__).resolve().parent
DATA_DIR = HARDWARE_DIR / "data"
MODELS_DIR = HARDWARE_DIR / "models"


def set_all_seeds(seed=SEED):
    np.random.seed(seed)


def _block_indices(blocks, block_size=BLOCK_SIZE, trim=EDGE_TRIM):
    return np.concatenate(
        [np.arange(b * block_size + trim, (b + 1) * block_size - trim) for b in blocks]
    )


def run_preprocessing():
    print("=" * 60)
    print("  PREPROCESSING & DATA SPLITTING PIPELINE")
    print("=" * 60)

    set_all_seeds(SEED)

    # 1. Load raw data generated by data_pipeline.py
    X = np.load(DATA_DIR / "hw_X.npy")
    y = np.load(DATA_DIR / "hw_y.npy")
    features = np.load(DATA_DIR / "hw_features.npy", allow_pickle=True)
    csi = np.load(DATA_DIR / "hw_csi.npy")

    print(
        f"  Loaded Raw X: {X.shape}, y: {y.shape}, Features: {features.shape}, CSI: {csi.shape}"
    )

    # 2. Block-Stratified Train / Val / Test Split
    N = len(y)
    num_blocks = N // BLOCK_SIZE
    block_y = np.array(
        [
            y[i * BLOCK_SIZE : (i + 1) * BLOCK_SIZE].mean() > 0.1
            for i in range(num_blocks)
        ]
    )

    sss = StratifiedShuffleSplit(n_splits=1, test_size=0.30, random_state=SEED)
    train_b, temp_b = next(sss.split(np.zeros(num_blocks), block_y))

    sss_val = StratifiedShuffleSplit(n_splits=1, test_size=0.50, random_state=SEED)
    val_sub, test_sub = next(sss_val.split(np.zeros(len(temp_b)), block_y[temp_b]))
    val_b = temp_b[val_sub]
    test_b = temp_b[test_sub]

    train_idx = _block_indices(train_b, BLOCK_SIZE)
    val_idx = _block_indices(val_b, BLOCK_SIZE)
    test_idx = _block_indices(test_b, BLOCK_SIZE)

    splits = {
        name: {"X": X[idx], "y": y[idx], "features": features[idx], "csi": csi[idx]}
        for name, idx in (("train", train_idx), ("val", val_idx), ("test", test_idx))
    }

    # 3. Scale engineered features (RobustScaler fit strictly on train)
    scaler = RobustScaler()
    splits["train"]["features_scaled"] = scaler.fit_transform(
        splits["train"]["features"]
    )
    splits["val"]["features_scaled"] = scaler.transform(splits["val"]["features"])
    splits["test"]["features_scaled"] = scaler.transform(splits["test"]["features"])

    # 4. Standardize raw 6 channels using train statistics
    raw_mean = splits["train"]["X"].mean(axis=(0, 1))
    raw_std = splits["train"]["X"].std(axis=(0, 1)) + 1e-8
    for s in splits.values():
        s["X"] = ((s["X"] - raw_mean) / raw_std).astype(np.float32)

    # 5. Save scaler parameters
    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    scaler_info = {
        "center": scaler.center_.tolist(),
        "scale": scaler.scale_.tolist(),
        "raw_mean": raw_mean.tolist(),
        "raw_std": raw_std.tolist(),
    }
    with open(MODELS_DIR / "scaler_params.json", "w") as f:
        json.dump(scaler_info, f, indent=2)

    # 6. Save split datasets to disk for downstream training script
    np.savez(
        DATA_DIR / "processed_splits.npz",
        train_X=splits["train"]["X"],
        train_y=splits["train"]["y"],
        train_feat=splits["train"]["features_scaled"],
        train_csi=splits["train"]["csi"],
        val_X=splits["val"]["X"],
        val_y=splits["val"]["y"],
        val_feat=splits["val"]["features_scaled"],
        val_csi=splits["val"]["csi"],
        test_X=splits["test"]["X"],
        test_y=splits["test"]["y"],
        test_feat=splits["test"]["features_scaled"],
        test_csi=splits["test"]["csi"],
    )

    print(
        "  [OK] Preprocessing complete. Processed splits saved to hardware/data/processed_splits.npz"
    )


if __name__ == "__main__":
    run_preprocessing()
