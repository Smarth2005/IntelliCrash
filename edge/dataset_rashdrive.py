#!/usr/bin/env python3

import csv
import os
import time
import math
import sys
import select
import termios
import tty

from pathlib import Path
from datetime import datetime
from zoneinfo import ZoneInfo
from smbus2 import SMBus


# ============================================================
# SENSOR SETTINGS
# ============================================================

I2C_BUS = 1
I2C_ADDRESS = 0x6B

WHO_AM_I = 0x0F
CTRL1_XL = 0x10
CTRL2_G = 0x11
CTRL3_C = 0x12
OUTX_L_G = 0x22
OUTX_L_A = 0x28

ACCEL_SENSITIVITY = 0.000122
GYRO_SENSITIVITY = 0.0175
GRAVITY = 9.80665

OUTPUT_DIR = Path("dataset")
SAMPLE_INTERVAL = 0.01

TIMEZONE = ZoneInfo("Asia/Kolkata")


# ============================================================
# GLOBAL VARIABLES
# ============================================================

recording = True
paused = False
label = "non_crash"
sample_count = 0


# ============================================================
# IST TIMESTAMP
# Format: YYYY-MM-DD HH.MM.SS.ffff
# ============================================================

def utc():
    return datetime.now(TIMEZONE).strftime(
        "%Y-%m-%d %H.%M.%S.%f"
    )[:-2]


# ============================================================
# SIGNED 16-BIT CONVERSION
# ============================================================

def signed16(low, high):
    value = (high << 8) | low
    return value - 65536 if value >= 32768 else value


# ============================================================
# READ SENSOR AXES
# ============================================================

def read_axes(bus, register):
    data = bus.read_i2c_block_data(
        I2C_ADDRESS, register, 6
    )

    return [
        signed16(data[0], data[1]),
        signed16(data[2], data[3]),
        signed16(data[4], data[5]),
    ]


# ============================================================
# CREATE UNIQUE CSV FILE
# ============================================================

def next_filename():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    number = 1

    while True:
        path = OUTPUT_DIR / f"imu_session_{number:04d}.csv"

        if not path.exists():
            return path

        number += 1


# ============================================================
# KEYBOARD CONTROLS
# ============================================================

def controls():
    print("P=Pause/Resume | C=Crash | N=Non-crash | R=Rash drive")
    print("S=Stop and save | Q=Quit | H=Help")


def keyboard():
    global paused, label, recording

    if not sys.stdin.isatty():
        return

    while select.select([sys.stdin], [], [], 0)[0]:
        key = sys.stdin.read(1).lower()

        if key == "p":
            paused = not paused

        elif key == "c":
            label = "crash"

        elif key == "n":
            label = "non_crash"

        elif key == "r":
            label = "rash_drive"

        elif key == "s":
            recording = False

        elif key == "q":
            recording = False

        elif key == "h":
            controls()


# ============================================================
# DISPLAY ONLY FIVE LIVE LINES
# ============================================================

def display_live(
    state,
    label,
    sample_count,
    accel_ms2,
    gyro_rads,
):
    # Return cursor to the beginning of the display.
    print("\033[H", end="")

    print(f"Status: {state:<12}                         ")
    print(
        f"Label: {label:<12} | Saved rows: {sample_count:<10}       "
    )

    print(
        f"Accel (m/s^2): X={accel_ms2[0]:7.3f} "
        f"Y={accel_ms2[1]:7.3f} Z={accel_ms2[2]:7.3f}       "
    )

    print(
        f"Gyro (rad/s):  X={gyro_rads[0]:7.3f} "
        f"Y={gyro_rads[1]:7.3f} Z={gyro_rads[2]:7.3f}       "
    )

    print(
        "P=Pause | C=Crash | N=Non-crash | R=Rash drive | S=Stop | Q=Quit"
    )

    sys.stdout.flush()


# ============================================================
# MAIN PROGRAM
# ============================================================

def main():
    global recording, sample_count

    bus = None
    terminal_settings = None
    csvfile = None
    filename = None

    try:
        print("Connecting to ISM330DHCX...")

        bus = SMBus(I2C_BUS)

        identity = bus.read_byte_data(
            I2C_ADDRESS, WHO_AM_I
        )

        if identity != 0x6B:
            raise RuntimeError(
                f"Unexpected WHO_AM_I value: 0x{identity:02X}. "
                "Check sensor wiring and I2C configuration."
            )

        print("Sensor detected successfully.")

        # Enable block data update and auto-increment.
        bus.write_byte_data(
            I2C_ADDRESS, CTRL3_C, 0x44
        )

        # Accelerometer: 104 Hz, +/- 4 g.
        bus.write_byte_data(
            I2C_ADDRESS, CTRL1_XL, 0x48
        )

        # Gyroscope: 104 Hz, +/- 2000 dps.
        bus.write_byte_data(
            I2C_ADDRESS, CTRL2_G, 0x4C
        )

        time.sleep(0.1)

        filename = next_filename()

        csvfile = open(
            filename,
            "x",
            newline="",
            encoding="utf-8",
        )

        columns = [
            "timestamp_ist",
            "elapsed_seconds",
            "sample_interval_seconds",
            "observed_polling_hz",
            "accel_x_raw",
            "accel_y_raw",
            "accel_z_raw",
            "gyro_x_raw",
            "gyro_y_raw",
            "gyro_z_raw",
            "accel_x_m_s2",
            "accel_y_m_s2",
            "accel_z_m_s2",
            "gyro_x_rad_s",
            "gyro_y_rad_s",
            "gyro_z_rad_s",
            "label",
        ]

        writer = csv.DictWriter(
            csvfile,
            fieldnames=columns,
        )

        writer.writeheader()
        csvfile.flush()

        print(f"CSV file: {filename}")
        print("Preparing live display...")
        time.sleep(1)

        # Enable single-key controls in an interactive terminal.
        if sys.stdin.isatty():
            terminal_settings = termios.tcgetattr(
                sys.stdin.fileno()
            )
            tty.setcbreak(sys.stdin.fileno())

        # Clear the terminal once; subsequent updates reuse five lines.
        print("\033[2J\033[H", end="")
        sys.stdout.flush()

        start = time.monotonic()
        previous = None

        # ====================================================
        # DATA COLLECTION LOOP
        # ====================================================

        while recording:
            loop_start = time.monotonic()

            keyboard()

            if not recording:
                break

            # Continue reading the sensor while paused.
            gyro = read_axes(bus, OUTX_L_G)
            accel = read_axes(bus, OUTX_L_A)

            now = time.monotonic()

            interval = (
                now - previous
                if previous is not None
                else None
            )

            previous = now

            hz = (
                1.0 / interval
                if interval is not None and interval > 0
                else None
            )

            # Convert accelerometer readings to m/s^2.
            accel_ms2 = [
                v * ACCEL_SENSITIVITY * GRAVITY
                for v in accel
            ]

            # Convert gyroscope readings to rad/s.
            gyro_rads = [
                v * GYRO_SENSITIVITY * math.pi / 180
                for v in gyro
            ]

            state = "PAUSED" if paused else "RECORDING"

            # Update the same five terminal lines.
            display_live(
                state,
                label,
                sample_count,
                accel_ms2,
                gyro_rads,
            )

            # Save every reading only while recording is active.
            if not paused:
                row = {
                    "timestamp_ist": datetime.now(
                        TIMEZONE
                    ).strftime("%Y-%m-%d %H.%M.%S.%f")[:-2],

                    "elapsed_seconds": round(
                        now - start, 6
                    ),

                    "sample_interval_seconds": (
                        round(interval, 6)
                        if interval is not None
                        else ""
                    ),

                    "observed_polling_hz": (
                        round(hz, 2)
                        if hz is not None
                        else ""
                    ),

                    "accel_x_raw": accel[0],
                    "accel_y_raw": accel[1],
                    "accel_z_raw": accel[2],

                    "gyro_x_raw": gyro[0],
                    "gyro_y_raw": gyro[1],
                    "gyro_z_raw": gyro[2],

                    "accel_x_m_s2": round(
                        accel_ms2[0], 6
                    ),

                    "accel_y_m_s2": round(
                        accel_ms2[1], 6
                    ),

                    "accel_z_m_s2": round(
                        accel_ms2[2], 6
                    ),

                    "gyro_x_rad_s": round(
                        gyro_rads[0], 6
                    ),

                    "gyro_y_rad_s": round(
                        gyro_rads[1], 6
                    ),

                    "gyro_z_rad_s": round(
                        gyro_rads[2], 6
                    ),

                    "label": label,
                }

                writer.writerow(row)
                sample_count += 1

                # Flush data every 50 saved rows.
                if sample_count % 50 == 0:
                    csvfile.flush()
                    os.fsync(csvfile.fileno())

            # Maintain an approximate 100 Hz polling target.
            elapsed_work = time.monotonic() - loop_start

            time.sleep(
                max(0, SAMPLE_INTERVAL - elapsed_work)
            )

    except KeyboardInterrupt:
        print("\nCtrl+C received.")

    except Exception as error:
        print(f"\nERROR: {error}")

    finally:
        if csvfile is not None:
            csvfile.flush()
            os.fsync(csvfile.fileno())
            csvfile.close()

        # Restore normal terminal input behavior.
        if terminal_settings is not None:
            try:
                termios.tcsetattr(
                    sys.stdin.fileno(),
                    termios.TCSADRAIN,
                    terminal_settings,
                )
            except Exception:
                pass

        if bus is not None:
            bus.close()

        # Move below the five-line display for the final message.
        print("\033[6;1H", end="")
        print("\nData collection ended.")
        print(f"Total saved rows: {sample_count}")

        if filename is not None:
            print(f"CSV saved: {filename}")


if __name__ == "__main__":
    main()